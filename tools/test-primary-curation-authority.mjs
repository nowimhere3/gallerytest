import assert from 'node:assert/strict';
import {installFakeIndexedDB, settle} from './lib/browser-test-env.mjs';
import {ProfileStore} from '../src/profile/profile-store.js';
import {SyncIdentity} from '../src/profile/sync-device.js';
import {V3_ASSOCIATION_STORE} from '../src/storage/profile-sync-store.js';
installFakeIndexedDB();
const p = new ProfileStore({identity:new SyncIdentity({}),associationStore:V3_ASSOCIATION_STORE});
await settle(); await p.whenFactsSettled();
const old=p.getProfileId(); const entry=await p.createProfile('Best'); const id=entry.id;
await p.setPrimaryCuration(id); assert.equal(p.getPrimaryProfileId(),id);
assert.equal((await p.getFullReplica()).primaryCuration.v,id);
await p.switchProfile(id); p.setProfileName('Renamed'); await p.whenLocalWritesSettled(); assert.equal(p.getPrimaryProfileId(),id);
await p.switchProfile(old); p.setFavorite('before.jpg',true); await p.switchProfile(id); p.setFavorite('after.jpg',true);
await p.whenLocalWritesSettled();
const r=await p.getFullReplica(); assert.equal(r.profiles[old].items['before.jpg'].favorite.v.on,true);
assert.equal(r.profiles[id].items['after.jpg'].favorite.v.on,true);
await p.deleteProfile(id); assert.equal(p.getPrimaryProfileId(),null); assert.equal(p.getPrimaryCurationFact().v,null);
await p.adoptMergedPrimaryCuration({v:'unknown',t:Date.now()+10000,d:'peer'}); assert.equal(p.getPrimaryProfileId(),null);
const stamp={t:Date.now()+20000,d:'peer'};
await p.adoptMergedReplica({profiles:{unknown:{name:{v:'Arrived',...stamp},items:{},tags:{}}},associations:{}});
assert.equal(p.getPrimaryProfileId(),'unknown','retained fact becomes effective when profile arrives');
p.setFavorite('inflight.jpg',true);
await p.adoptMergedReplica({profiles:{},associations:{},primaryCuration:p.getPrimaryCurationFact()});
await p.whenLocalWritesSettled();
assert.equal((await p.getFullReplica()).profiles[p.getProfileId()].items['inflight.jpg'].favorite.v.on,true,'sync adoption preserves in-flight heart');
const q=new ProfileStore({identity:new SyncIdentity({}),associationStore:V3_ASSOCIATION_STORE});
await settle(); await q.whenFactsSettled(); assert.deepEqual(q.getPrimaryCurationFact(),p.getPrimaryCurationFact());
await p.setPrimaryCuration(old);
for(let attempt=0;attempt<30 && q.getPrimaryProfileId()!==old;attempt++) await settle();
assert.equal(q.getPrimaryProfileId(),old,'Primary invalidation reloads sibling authority');
await p.setPrimaryCuration(null);
for(let attempt=0;attempt<30 && q.getPrimaryCurationFact()?.v!==null;attempt++) await settle();
assert.equal(q.getPrimaryCurationFact().v,null,'stamped Off reaches sibling');
console.log('PASS Primary authority, rename, deletion, unknown target, reload and atomic favorites'); process.exit(0);
